# ============ 颗粒日期码 · 批量（多张小图一次读）============
def crops(n: int, want: str) -> str:
    """n=图片张数；want=期望数字位数说明。注意 JSON 花括号用 {{ }} 转义。"""
    return (f"下面是 {n} 张内存条芯片上「日期码」的局部特写，依次是第 1 到第 {n} 张。"
            f"请逐张读出其中的日期数字（{want}），严格按顺序只输出 JSON 数组，"
            f'形如 [{{"i":1,"digits":"534"}}, ...]，i 与图片顺序一致；读不出则 digits 为空字符串。不要多余文字。')


# ============ 颗粒日期码 · 单颗（单张小图，兜底用，最准）============
# 【务必保留"只许取 SEC 那一行"的约束】实测漏掉它会造成**静默错读**：
# 颗粒底部还有一串料号（如 QRY40623C / QRG20918P），里面全是数字。
# 早前的提示词只说"读日期数字"，模型就从料号里截了 3 位 —— 槽3 明明整槽
# 都是 SEC 516，却返回 406/486/516 三种（406 来自 QRY40623C）。
# 后果极严重：按业务铁律禁止多数表决，这种错读会被当成"某几颗被偷换"
# 判不合格并定位到具体颗号，全是假阳性；反之真被偷换的那颗也会被淹没。
def crop(want: str) -> str:
    return (f"这是内存条【一颗】存储芯片(三星 DRAM)的丝印特写。请读出【日期码】。\n"
            f"位置规则（必须严格遵守）：\n"
            f"1. 日期码在芯片丝印的【第一行】，紧跟在 'SEC' 之后，是 {want}。\n"
            f"2. 芯片【底部】还有一行较长的料号/批次号（例如 QRY40623C、QRG20918P），"
            f"里面也含数字，但那**不是日期码**，绝对不要从这一行取数字。\n"
            f"3. 中间几行是型号（如 K4RAH04 / 6VP BCWM），也不是日期。\n"
            f"只有在第一行 'SEC' 后面确实看清了数字时才输出；"
            f"若第一行看不清或图中没有 'SEC' 行，digits 就留空 —— "
            f"**留空是可以接受的，从错误的行猜一个数字是绝对不允许的**。\n"
            f"注意区分易混字符：字母 O 不是数字 0、S 不是 5、B 不是 8。\n"
            f'只输出 JSON：{{"digits":"第一行 SEC 后的数字，读不出为空","raw":"你看到的第一行原文"}}，不要多余文字。')


# ============ PMIC（电源管理芯片）日期码 ============
# 【务必保留行位置约束】这颗丝印竖排四行，形如：
#   MPS2522 / MP8895F / T244E99 / 18-61
# 日期在**第一行 MPS 之后**（2522 = 2025年第22周）。早前不给行约束时，
# 模型四槽全返回 1861 —— 那是第四行的 18-61，且四槽都一样，
# 错得非常隐蔽（看不出异常，会被当成"四根同批次"放过）。
PMIC_DATE = """这是内存条上 PMIC（电源管理芯片，MPS 品牌）的丝印特写，丝印共有四行。
请读出【日期码】，位置规则（必须严格遵守）：
1. 日期码在【第一行】，紧跟在字母 'MPS' 之后，是 4 位数字 YYWW（前2位年份、后2位周数 1~53），
   例如第一行是 'MPS2522' 则日期码为 2522（2025年第22周）。
2. 第二行是型号（如 MP8895F）、第三行是批次（如 T244E99）、
   第四行形如 '18-61' 或 '18-62' —— 这三行**都不是日期码**，绝对不要从它们取数字。
   特别注意：不要把第四行的 18-61 当成 1861 输出。
3. **只要你在 raw 里写出了第一行是 'MPS' 加 4 位数字，就必须把那 4 位填进 digits。**
   看清了却留空是错误的 —— 留空只适用于第一行确实没看清的情况。
只有在第一行 'MPS' 后面确实看清了 4 位数字时才输出；看不清就留空。
**留空是可以接受的，从错误的行猜一个数字是绝对不允许的。**
只输出 JSON：{"digits":"第一行MPS后的4位数字，读不出为空","raw":"你看到的四行原文"}，不要多余文字。"""


