# 颗粒位数说明（dram=3位 YWW / 其他=4位 YYWW），供 crops/crop 复用
def want_text(kind: str) -> str:
    return "3 位数字(YWW，如 534)" if kind == "dram" else "4 位数字(YYWW，如 2517)"


